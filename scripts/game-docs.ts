/**
 * Writes the readable game bible from the game data, so the documents can never disagree with
 * the code. SPOILERS: these files contain the solution.
 *
 * npm run game:docs
 */
import { writeFileSync } from "node:fs";
import { characters, circles, exhibits, facts, props, questions, races, survivors, markers } from "@/data/game";
import { renderObjective } from "@/data/game";
import { timeline } from "@/data/game/story";
import { formatReport, runValidation } from "@/lib/game/validate";

const out = (name: string, text: string) => writeFileSync(`docs/game/${name}`, `${text.trim()}\n`);
const cname = (id: string) => characters.find((character) => character.id === id)?.name ?? id;

// ---------------------------------------------------------------- cast
{
  const lines = ["# The cast", "", "*Generated by `npm run game:docs` from `src/data/game`. Edit the data, not this file. **Spoilers.** Five groups: the five survivors, and four trades.*", ""];
  for (const circle of circles) {
    lines.push(`## ${circle.name}`, `*${circle.blurb}*`, "");
    lines.push("| Character | Real guest | Role | Starts with | Small secret (what others can learn) |", "|---|---|---|---|---|");
    for (const character of characters.filter((entry) => entry.circle === circle.id)) {
      const role = character.survivor ? `**SURVIVOR** ${character.survivor.veilName}, ${character.survivor.veilTitle}, marker ${character.survivor.markerNo}` : character.role ? character.role : "";
      lines.push(`| **${character.name}**<br>${character.occupation} | ${character.realNames[0]} | ${role} | $${character.startingCash}${character.carries.length ? `; ${character.carries.join(", ")}` : ""} | ${character.smallSecret.text} (confidant: ${cname(character.smallSecret.confidant)}) |`);
    }
    lines.push("");
  }
  lines.push("## The five survivors", "");
  lines.push("| Cover | Real identity | Tell (do it 3 times) | Skill that leaks | Why they want him dead (their errand to learn) |", "|---|---|---|---|---|");
  for (const survivor of survivors) {
    const info = survivor.survivor!;
    lines.push(`| ${survivor.name} | ${info.veilName}, ${info.veilTitle} (marker ${info.markerNo}) | ${info.tell} | ${info.skillLeak} | ${info.grievance} |`);
  }
  lines.push("", "## Decoys (innocent people with a survivor's habit)", "");
  for (const character of characters.filter((entry) => entry.habit)) lines.push(`- **${character.name}**: ${character.habit}`);
  lines.push("", "## Public bios and backgrounds", "");
  for (const character of characters) {
    lines.push(`### ${character.name}`, `*${character.occupation}* · ${circles.find((c) => c.id === character.circle)!.name}`, "", `**Public.** ${character.publicBio}`, "", `**Background.** ${character.background.history}`, "", ...character.background.people.map((line) => `- ${line}`), "", `**Wear.** ${character.background.wardrobe}`, "");
  }
  out("02-cast.md", lines.join("\n"));
}

// ---------------------------------------------------------------- objectives
{
  const lines = ["# Every objective", "", "*Generated. Five per guest, one point each, 5 for everyone. **Spoilers**: answers are shown.*", ""];
  for (const character of characters) {
    lines.push(`## ${character.name}`, "");
    for (const objective of character.objectives) {
      const rendered = renderObjective(objective);
      const check = objective.check;
      const answer =
        check.kind === "code" ? `code ${check.codes.join(" / ")}`
        : check.kind === "pattern" ? check.all.map((group) => `[${group.join(" | ")}]`).join(" AND ")
        : check.kind === "money" ? `at least $${check.min}`
        : check.kind === "clock" ? `${check.from} to ${check.to}`
        : check.kind === "approval" ? `the host confirms it in person and gives the approval word "${check.word}"`
        : check.kind === "keep" ? `${cname(check.seeker)} learns it (${check.seekerObjective}) and ${cname(check.rival)} does not (${check.rivalObjective})`
        : check.kind;
      lines.push(`${objective.id}. **${rendered.title}** (${objective.kind}, ${objective.points}) ${rendered.text}`, `   - answer: ${answer}${objective.with.length ? `; from ${[...objective.with, ...(objective.alsoFrom ?? [])].map(cname).join(", ")}` : ""}`);
    }
    lines.push("");
  }
  lines.push("## The group races (+1 for the first in each group)", "");
  for (const race of races) {
    const members = characters.filter((character) => character.circle === race.circle).map((character) => character.name).join(", ");
    lines.push(`### ${circles.find((circle) => circle.id === race.circle)!.name}: ${race.title}`, "", race.text, "", `Members: ${members}`);
    if (race.tokens.length) lines.push(`Slips (held by guests outside the group): ${race.tokens.map((token) => { const prop = props.find((item) => item.id === token)!; return `${prop.code} (${cname(prop.carriedBy!)})`; }).join(", ")}`);
    else lines.push("Decided by the House: the first survivor to buy the vial.");
    lines.push("");
  }
  lines.push("## Approval words (give one only after you have seen it happen)", "", "| Guest | Objective | Word |", "|---|---|---|");
  for (const character of characters) for (const objective of character.objectives) if (objective.check.kind === "approval") lines.push(`| ${character.name} | ${objective.title} | ${objective.check.word} |`);
  lines.push("");
  out("03-objectives.md", lines.join("\n"));
}

// ---------------------------------------------------------------- clues and props
{
  const lines = ["# Clues, pages and props", "", "*Generated. **Spoilers.***", "", "## The clue web", "", "Every fact below is held by at least three guests (or two plus a printed page).", ""];
  for (const fact of facts) {
    lines.push(`### ${fact.id} (${fact.kind})`, fact.truth, "");
    for (const holder of fact.holders) lines.push(`- **${cname(holder.guest)}** [${holder.share}]: ${holder.line}`);
    if (fact.exhibits?.length) lines.push(`- printed: ${fact.exhibits.join(", ")}`);
    lines.push("");
  }
  lines.push("## Printed pages", "");
  lines.push("| Code | Page | Lives | Appears |", "|---|---|---|---|");
  for (const exhibit of exhibits) lines.push(`| ${exhibit.code} | ${exhibit.title} | ${exhibit.where}${exhibit.heldBy ? ` (${cname(exhibit.heldBy)})` : ""} | ${exhibit.appears} |`);
  lines.push("", "## Props (fill in `assigned` and the hints after the house scan)", "");
  lines.push("| Code | Prop | Could be | Where | Hint or carrier |", "|---|---|---|---|---|");
  for (const prop of props) lines.push(`| ${prop.code} | ${prop.name} | ${prop.generic} | ${prop.placement} | ${prop.placement === "carried" ? cname(prop.carriedBy!) : prop.hint} |`);
  lines.push("", "## Markers (one per survivor)", "", "| Marker | Code | Belongs to |", "|---|---|---|");
  for (const marker of markers) lines.push(`| ${marker.no} | ${marker.code} | ${survivors.find((s) => s.survivor!.markerNo === marker.no)!.name} |`);
  out("04-clues-and-props.md", lines.join("\n"));
}

// ---------------------------------------------------------------- printables
{
  const lines = ["# Print list", "", "*Generated. Everything to print, cut or write out. **Spoilers.***", "", "## Pages for the binder, the table and the envelopes", ""];
  for (const exhibit of exhibits) {
    lines.push(`### ${exhibit.title} — ${exhibit.where}${exhibit.heldBy ? `, in ${cname(exhibit.heldBy)}'s envelope` : ""}${exhibit.appears === "scene" ? " (lay out at 8:35)" : ""}`, "", "```", ...exhibit.body, "```", "");
  }
  lines.push("## Tags (small black stickers or folded paper, one per object)", "", ...props.map((prop) => `- ${prop.code}: ${prop.name}`), "");
  lines.push("## Markers (five cards, black, gold No.)", "", ...markers.map((marker) => `- MARKER No. ${marker.no} — code ${marker.code} — “Honoured by the House”`), "");
  lines.push("## Currency", "", `House bills: $100 each. Cash in the room at the start: $${characters.reduce((sum, character) => sum + character.startingCash, 0).toLocaleString("en-US")} (${characters.reduce((sum, character) => sum + character.startingCash, 0) / 100} bills, so the rest of your 400 stay with Bartend Joe for change and winnings).`, ...characters.map((character) => `- ${character.name}: ${character.startingCash / 100} bills ($${character.startingCash})`), "");
  lines.push("## Standby slips (the Dead Letter box, opened at 9:15)", "", "One slip per clue errand. Hand it to a guest whose named sources did not come.", "");
  for (const character of characters) {
    for (const objective of character.objectives) {
      if (objective.check.kind !== "pattern" || objective.kind === "role") continue;
      const source = characters.find((entry) => entry.id === objective.with[0]);
      const answer = source ? [...source.secrets.map((l) => l.text), source.smallSecret.text, ...facts.flatMap((fact) => fact.holders.filter((h) => h.guest === source.id).map((h) => h.line))].find((line) => objective.check.kind === "pattern" && objective.check.all.every((group) => group.some((term) => line.toLowerCase().includes(term.toLowerCase())))) : undefined;
      lines.push(`- **${objective.id}** (${character.name}): ${answer ?? "see " + objective.id + " in 03-objectives.md"}`);
    }
  }
  lines.push("", "## Each guest's envelope", "", ...characters.map((character) => `- ${character.name}: ${[`${character.startingCash / 100} bills ($${character.startingCash})`, ...character.carries.map((id) => props.find((p) => p.id === id)!.name), character.survivor ? `marker No. ${character.survivor.markerNo}` : ""].filter(Boolean).join(", ")}`));
  out("05-print-list.md", lines.join("\n"));
}

// ---------------------------------------------------------------- the story
{
  const lines = ["# Timeline", "", ...timeline.map((entry) => `- **${entry.when}**: ${entry.what}`), "", "## The nine final questions", ""];
  for (const question of questions) lines.push(`- **${question.id}** (${question.points}): ${question.prompt}`);
  out("01-timeline-and-questions.md", lines.join("\n"));
}

out("07-validation-report.md", `# Validation report\n\n*Generated by \`npm run game:docs\`.*\n\n\`\`\`\n${formatReport(runValidation())}\n\`\`\``);
// ---------------------------------------------------------------- the game master's guide
{
  const bills = (amount: number) => `${amount / 100} bills ($${amount.toLocaleString("en-US")})`;
  const label = (character: (typeof characters)[number], objective: (typeof character.objectives)[number]) => {
    const check = objective.check;
    const prop = objective.prop ? props.find((item) => item.id === objective.prop) : undefined;
    const partner = objective.with[0] ? cname(objective.with[0]) : "";
    switch (check.kind) {
      case "money": return `Money: finish with at least $${check.min.toLocaleString("en-US")}`;
      case "approval": return `Host task: ${objective.title} (word: **${check.word}**)`;
      case "keep": return `Keep a secret: tell ${cname(check.seeker)}, hide it from ${cname(check.rival)} (sellable, $200)`;
      case "vial-attempt": return "Offer a marker to the Butler (the vial)";
      case "butler-sale": return "Sell the vial (the Butler)";
      case "pattern": return objective.kind === "learn" && objective.id.endsWith("-secret") ? `Learn ${partner}'s small secret` : `Learn: ${objective.title}`;
      case "code":
        if (objective.kind === "find") return `Find the ${prop?.name} (${prop?.generic})`;
        if (objective.kind === "swap") return `Swap with ${partner}, receive the ${prop?.name}`;
        return `Deal: ${objective.title}`;
      default: return objective.title;
    }
  };
  const lines: string[] = [];
  lines.push("# Game master's guide", "", "*Generated by `npm run game:docs`. **Spoilers.** Everything you need to run, check and grade the night. Your role: Bartend Joe, never a suspect, never scoring.*", "");
  lines.push("## 1. The game on one page", "");
  lines.push("- 24 guests, 5 groups: the five survivors (secret), and four trades (order, stage, working, river). The Butler (Rebecca) is in the river group.");
  lines.push("- Each guest has **5 objectives** (1 point each) and answers **9 mystery questions** (10 points). They also **name up to 4 survivors** (+1 right, -0.5 wrong).");
  lines.push("- Each group has a **race**: the first to type any 3 of its 5 slip codes gets +1. The survivors' race is buying the House's vial.");
  lines.push("- **Wallet bonus**: the quarter of the room that ends best off against where they started (most gained, or least spent) gets +1. A money errand counts from its target.");
  lines.push("- **Maximum 21**: objectives 5 + survivors 4 + mysteries 10 + race 1 + wallet 1.");
  lines.push("- **Money**: everyone starts with $100 bills. Some clues cost a bill in the House Tin at the bar. A kept secret can be sold for $200 (a sale to the keeper's rival costs the keeper half a point).");
  lines.push("- **The game runs itself**: it opens at 8:00, the House closes at 9:00, the book closes at 10:30. You use /admin only at the end.", "");
  lines.push("## 2. The night, minute by minute", "", "| Time | What happens | You |", "|---|---|---|");
  lines.push("| Before 8:00 | Envelopes handed out at the door | Hand each guest their black envelope |");
  lines.push("| **8:00** | Every card, objective and group race opens by itself | Tend bar. (The **Start game** button on /admin only opens early.) |");
  lines.push("| Before 8:30 | Josh tells you the minute he thinks the scream will come | Write it on a card, seal it |");
  lines.push("| **8:30** | Silas's five-minute spotlight (and Anika's request) | Enjoy it, give Silas his word after |");
  lines.push("| 8:35 to 9:00 | The Butler sells the vial once to the first marker | Watch the House panel |");
  lines.push("| **9:00** | The House closes by itself; the nightcap is served | Note the buyer; stage the body at ~9:05 |");
  lines.push("| ~9:15 | The Butler finds him and screams; the Sheriff takes charge | Open Josh's envelope afterwards |");
  lines.push("| 9:15 to 10:15 | Investigation; the Sheriff arrests by 10:15 | Open the Dead Letter box for guests whose source is absent |");
  lines.push("| 10:00 | Wrap-up: read Cassie's letter. Give Eric the charter; give Leon a bulletin to read aloud | ~3 minutes |");
  lines.push("| **10:30** | The book closes by itself | Start grading |", "");
  lines.push("## 3. Approval words (only you have these)", "", "A guest does the real task, taps **Claim this point**, and finds you. Once you have seen it happen, say the word. Never before.", "", "| Guest | Task | Word |", "|---|---|---|");
  for (const character of characters) for (const objective of character.objectives) if (objective.check.kind === "approval") lines.push(`| ${character.name} | ${objective.title} | **${objective.check.word}** |`);
  lines.push("");
  lines.push("## 4. Every guest, in their group", "");
  for (const circle of circles) {
    lines.push(`### ${circle.name}`, "");
    for (const character of characters.filter((entry) => entry.circle === circle.id)) {
      const role = character.survivor ? `SURVIVOR: really ${character.survivor.veilName}, ${character.survivor.veilTitle}, marker ${character.survivor.markerNo}` : character.role ? character.role : character.occupation;
      lines.push(`**${character.name}** (${character.realNames[0]}), ${role}. Starts with ${bills(character.startingCash)}${character.carries.length ? `; carries ${character.carries.map((id) => props.find((item) => item.id === id)?.name ?? id).join(", ")}` : ""}.`, "");
      character.objectives.forEach((objective, index) => lines.push(`${index + 1}. ${label(character, objective)}`));
      lines.push("");
    }
  }
  lines.push("## 5. The group races", "", "| Group | Race | Slips (who carries them) |", "|---|---|---|");
  for (const race of races) lines.push(`| ${circles.find((circle) => circle.id === race.circle)?.name} | ${race.title} | ${race.tokens.length ? `${race.tokens.length} slips, need ${race.need}: ${race.tokens.map((token) => cname(props.find((item) => item.id === token)?.carriedBy ?? "")).join(", ")}` : "the House's vial: the first marker the Butler accepts"} |`);
  lines.push("");
  lines.push("## 6. Objects", "", "**Hidden finds** (the tag stays on the object; nobody moves anything):", "", "| Tag code | Game name | Real object | Who must find it |", "|---|---|---|---|");
  for (const prop of props.filter((item) => item.placement === "hidden")) {
    const finders = characters.filter((character) => character.objectives.some((objective) => objective.kind === "find" && objective.prop === prop.id)).map((character) => character.id[0].toUpperCase() + character.id.slice(1));
    lines.push(`| ${prop.code} | ${prop.name} | ${prop.generic} | ${finders.join(", ")} |`);
  }
  lines.push("", "**Passed around** (handed out at the door, change hands by a deal):", "", "| Tag code | Game name | Real object | Starts with |", "|---|---|---|---|");
  for (const prop of props.filter((item) => item.placement === "carried" && !/^(witness|reply|tool|trade)-/.test(item.id))) lines.push(`| ${prop.code} | ${prop.name} | ${prop.generic} | ${cname(prop.carriedBy ?? "")} |`);
  lines.push("", "Race slips are printed on `slips.pdf` (the `witness`, `reply`, `tool` and `trade` slips).", "", "**Still to choose:** a real earring (Tiffany), a small jar (Tim) and a baseball (Arjun) for the three swap items that are not yet in your photos.", "");
  lines.push("## 7. The questions", "", "Everyone answers nine: old-1 to old-3, new-1 to new-3 and con-1 to con-3. **The Butler and the killer answer alt-1 and alt-2 instead of new-1 and new-2**: the Butler knows who bought the vial and the killer knows who poured it, so the who and how questions would be free for them.", "", "| | Question | Points |", "|---|---|---|");
  for (const question of questions) lines.push(`| ${question.id} | ${question.prompt} | ${question.points} |`);
  lines.push("");
  lines.push("## 8. Money, in one place", "", `- Cash in the room: $${characters.reduce((sum, character) => sum + character.startingCash, 0).toLocaleString("en-US")} (${characters.reduce((sum, character) => sum + character.startingCash, 0) / 100} bills). Keep the rest of your 400 in the House Tin at the bar for change.`, "- A clue tagged **Costs $100 at the bar**: the guest drops a bill in the House Tin, then the holder tells them. Honour system.", "- A kept secret can be sold for $200. A sale to the keeper's rival costs the keeper half a point; a sale to the seeker costs nothing.", "- At the end everyone types the bills they hold. You do not count; at grading you ask to see the bills of the people the packet lists.", "");
  lines.push("## 9. Grading, about fifteen minutes", "", "1. `npm run game:grade -- grade`", "2. `npm run game:grade -- packet`, then judge it and write `verdicts.json`.", "3. `npm run game:grade -- verdicts verdicts.json`", "4. `npm run game:grade -- standings`. If it says TIED FOR FIRST, ask the secret tie-breaker aloud (the second rail stub in the jacket lining).", "5. Check the bills of the guests the packet lists under money claims and wallet bonus.", "6. `npm run game:grade -- publish`, then read out the winner.", "");
  lines.push("## 10. If something goes wrong", "", "| Problem | What to do |", "|---|---|", "| The Butler is absent | `npm run game:grade -- assign-vial <slug>` for the first survivor who asks at the bar. The Butler's own errands are stranded. |", "| Nobody buys the vial by 9:00 | `npm run game:grade -- assign-vial <slug>`. |", "| A survivor is absent | Their marker is never offered. |", "| Any other guest is absent | Their partner trades with you using the standby tray at the bar. A guest with no submissions and no House events counts as absent. |", "| A phone does not work | They write answers on paper; type them in with **Sign in as** on /admin, or tell them to sign in with /resume. |", "| You pressed Start too early | `npm run game:grade -- stop` seals everything again. |", "| Before the night, once | Run the database migration (`drizzle-kit migrate`): half points will not save without it. |", "");
  lines.push("## 11. Your checklist", "");
  for (const item of [
    "Printed everything in `docs/print/game/`, including `host-sheet.pdf` and `tag-key.pdf`",
    "Every black envelope has its sheet, carried items, slips and starting bills (survivors: invitation, marker, flap; checked twice)",
    "Every tag code on the right object (section 6) and in shared rooms only",
    "Race slips in the right hands (section 5); standby tray at the bar",
    "The House Tin, the House Book, the vial and its three decoys are at the bar",
    "The Keeper's table is laid out; the scene card is in your pocket; the second rail stub is in the jacket lining",
    "Approval words (section 3) are on the host sheet and nowhere else",
    "Migration run; /game opens on a phone; /admin opens on your laptop",
    "400 bills counted; the leftover stay in the House Tin",
  ]) lines.push(`- [ ] ${item}`);
  out("00-game-master-guide.md", lines.join("\n"));
}

