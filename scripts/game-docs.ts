/**
 * Writes the readable game bible from the game data, so the documents can never disagree with
 * the code. SPOILERS: these files contain the solution.
 *
 * npm run game:docs
 */
import { writeFileSync } from "node:fs";
import { characters, circles, exhibits, facts, props, questions, races, survivors, markers } from "@/data/game";
import { renderObjective } from "@/data/game";
import { timeline } from "@/data/game/story";
import { formatReport, runValidation } from "@/lib/game/validate";

const out = (name: string, text: string) => writeFileSync(`docs/game/${name}`, `${text.trim()}\n`);
const cname = (id: string) => characters.find((character) => character.id === id)?.name ?? id;

// ---------------------------------------------------------------- cast
{
  const lines = ["# The cast", "", "*Generated by `npm run game:docs` from `src/data/game`. Edit the data, not this file. **Spoilers.** Five groups: the five survivors, and four trades.*", ""];
  for (const circle of circles) {
    lines.push(`## ${circle.name}`, `*${circle.blurb}*`, "");
    lines.push("| Character | Real guest | Role | Starts with | Small secret (what others can learn) |", "|---|---|---|---|---|");
    for (const character of characters.filter((entry) => entry.circle === circle.id)) {
      const role = character.survivor ? `**SURVIVOR** ${character.survivor.veilName}, ${character.survivor.veilTitle}, marker ${character.survivor.markerNo}` : character.role ? character.role : "";
      lines.push(`| **${character.name}**<br>${character.occupation} | ${character.realNames[0]} | ${role} | $${character.startingCash}${character.carries.length ? `; ${character.carries.join(", ")}` : ""} | ${character.smallSecret.text} (confidant: ${cname(character.smallSecret.confidant)}) |`);
    }
    lines.push("");
  }
  lines.push("## The five survivors", "");
  lines.push("| Cover | Real identity | Tell (do it 3 times) | Skill that leaks | Why they want him dead (their errand to learn) |", "|---|---|---|---|---|");
  for (const survivor of survivors) {
    const info = survivor.survivor!;
    lines.push(`| ${survivor.name} | ${info.veilName}, ${info.veilTitle} (marker ${info.markerNo}) | ${info.tell} | ${info.skillLeak} | ${info.grievance} |`);
  }
  lines.push("", "## Decoys (innocent people with a survivor's habit)", "");
  for (const character of characters.filter((entry) => entry.habit)) lines.push(`- **${character.name}**: ${character.habit}`);
  lines.push("", "## Public bios and backgrounds", "");
  for (const character of characters) {
    lines.push(`### ${character.name}`, `*${character.occupation}* · ${circles.find((c) => c.id === character.circle)!.name}`, "", `**Public.** ${character.publicBio}`, "", `**Background.** ${character.background.history}`, "", ...character.background.people.map((line) => `- ${line}`), "", `**Wear.** ${character.background.wardrobe}`, "");
  }
  out("02-cast.md", lines.join("\n"));
}

// ---------------------------------------------------------------- objectives
{
  const lines = ["# Every objective", "", "*Generated. Five per guest, one point each, 5 for everyone. **Spoilers**: answers are shown.*", ""];
  for (const character of characters) {
    lines.push(`## ${character.name}`, "");
    for (const objective of character.objectives) {
      const rendered = renderObjective(objective);
      const check = objective.check;
      const answer =
        check.kind === "code" ? `code ${check.codes.join(" / ")}`
        : check.kind === "pattern" ? check.all.map((group) => `[${group.join(" | ")}]`).join(" AND ")
        : check.kind === "money" ? `at least $${check.min}`
        : check.kind === "clock" ? `${check.from} to ${check.to}`
        : check.kind === "approval" ? `the host confirms it in person and gives the approval word "${check.word}"`
        : check.kind === "keep" ? `${cname(check.seeker)} learns it (${check.seekerObjective}) and ${cname(check.rival)} does not (${check.rivalObjective})`
        : check.kind;
      lines.push(`${objective.id}. **${rendered.title}** (${objective.kind}, ${objective.points}) ${rendered.text}`, `   - answer: ${answer}${objective.with.length ? `; from ${[...objective.with, ...(objective.alsoFrom ?? [])].map(cname).join(", ")}` : ""}`);
    }
    lines.push("");
  }
  lines.push("## The group races (+1 for the first in each group)", "");
  for (const race of races) {
    const members = characters.filter((character) => character.circle === race.circle).map((character) => character.name).join(", ");
    lines.push(`### ${circles.find((circle) => circle.id === race.circle)!.name}: ${race.title}`, "", race.text, "", `Members: ${members}`);
    if (race.tokens.length) lines.push(`Slips (held by guests outside the group): ${race.tokens.map((token) => { const prop = props.find((item) => item.id === token)!; return `${prop.code} (${cname(prop.carriedBy!)})`; }).join(", ")}`);
    else lines.push("Decided by the House: the first survivor to buy the vial.");
    lines.push("");
  }
  lines.push("## Approval words (give one only after you have seen it happen)", "", "| Guest | Objective | Word |", "|---|---|---|");
  for (const character of characters) for (const objective of character.objectives) if (objective.check.kind === "approval") lines.push(`| ${character.name} | ${objective.title} | ${objective.check.word} |`);
  lines.push("");
  out("03-objectives.md", lines.join("\n"));
}

// ---------------------------------------------------------------- clues and props
{
  const lines = ["# Clues, pages and props", "", "*Generated. **Spoilers.***", "", "## The clue web", "", "Every fact below is held by at least three guests (or two plus a printed page).", ""];
  for (const fact of facts) {
    lines.push(`### ${fact.id} (${fact.kind})`, fact.truth, "");
    for (const holder of fact.holders) lines.push(`- **${cname(holder.guest)}** [${holder.share}]: ${holder.line}`);
    if (fact.exhibits?.length) lines.push(`- printed: ${fact.exhibits.join(", ")}`);
    lines.push("");
  }
  lines.push("## Printed pages", "");
  lines.push("| Code | Page | Lives | Appears |", "|---|---|---|---|");
  for (const exhibit of exhibits) lines.push(`| ${exhibit.code} | ${exhibit.title} | ${exhibit.where}${exhibit.heldBy ? ` (${cname(exhibit.heldBy)})` : ""} | ${exhibit.appears} |`);
  lines.push("", "## Props (fill in `assigned` and the hints after the house scan)", "");
  lines.push("| Code | Prop | Could be | Where | Hint or carrier |", "|---|---|---|---|---|");
  for (const prop of props) lines.push(`| ${prop.code} | ${prop.name} | ${prop.generic} | ${prop.placement} | ${prop.placement === "carried" ? cname(prop.carriedBy!) : prop.hint} |`);
  lines.push("", "## Markers (one per survivor)", "", "| Marker | Code | Belongs to |", "|---|---|---|");
  for (const marker of markers) lines.push(`| ${marker.no} | ${marker.code} | ${survivors.find((s) => s.survivor!.markerNo === marker.no)!.name} |`);
  out("04-clues-and-props.md", lines.join("\n"));
}

// ---------------------------------------------------------------- printables
{
  const lines = ["# Print list", "", "*Generated. Everything to print, cut or write out. **Spoilers.***", "", "## Pages for the binder, the table and the envelopes", ""];
  for (const exhibit of exhibits) {
    lines.push(`### ${exhibit.title} — ${exhibit.where}${exhibit.heldBy ? `, in ${cname(exhibit.heldBy)}'s envelope` : ""}${exhibit.appears === "scene" ? " (lay out at 8:35)" : ""}`, "", "```", ...exhibit.body, "```", "");
  }
  lines.push("## Tags (small black stickers or folded paper, one per object)", "", ...props.map((prop) => `- ${prop.code}: ${prop.name}`), "");
  lines.push("## Markers (five cards, black, gold No.)", "", ...markers.map((marker) => `- MARKER No. ${marker.no} — code ${marker.code} — “Honoured by the House”`), "");
  lines.push("## Currency", "", `House bills: $100 each. Cash in the room at the start: $${characters.reduce((sum, character) => sum + character.startingCash, 0).toLocaleString("en-US")} (${characters.reduce((sum, character) => sum + character.startingCash, 0) / 100} bills, so the rest of your 400 stay with Bartend Joe for change and winnings).`, ...characters.map((character) => `- ${character.name}: ${character.startingCash / 100} bills ($${character.startingCash})`), "");
  lines.push("## Standby slips (the Dead Letter box, opened at 9:15)", "", "One slip per clue errand. Hand it to a guest whose named sources did not come.", "");
  for (const character of characters) {
    for (const objective of character.objectives) {
      if (objective.check.kind !== "pattern" || objective.kind === "role") continue;
      const source = characters.find((entry) => entry.id === objective.with[0]);
      const answer = source ? [...source.secrets.map((l) => l.text), source.smallSecret.text, ...facts.flatMap((fact) => fact.holders.filter((h) => h.guest === source.id).map((h) => h.line))].find((line) => objective.check.kind === "pattern" && objective.check.all.every((group) => group.some((term) => line.toLowerCase().includes(term.toLowerCase())))) : undefined;
      lines.push(`- **${objective.id}** (${character.name}): ${answer ?? "see " + objective.id + " in 03-objectives.md"}`);
    }
  }
  lines.push("", "## Each guest's envelope", "", ...characters.map((character) => `- ${character.name}: ${[`${character.startingCash / 100} bills ($${character.startingCash})`, ...character.carries.map((id) => props.find((p) => p.id === id)!.name), character.survivor ? `marker No. ${character.survivor.markerNo}` : ""].filter(Boolean).join(", ")}`));
  out("05-print-list.md", lines.join("\n"));
}

// ---------------------------------------------------------------- the story
{
  const lines = ["# Timeline", "", ...timeline.map((entry) => `- **${entry.when}**: ${entry.what}`), "", "## The nine final questions", ""];
  for (const question of questions) lines.push(`- **${question.id}** (${question.points}): ${question.prompt}`);
  out("01-timeline-and-questions.md", lines.join("\n"));
}

out("07-validation-report.md", `# Validation report\n\n*Generated by \`npm run game:docs\`.*\n\n\`\`\`\n${formatReport(runValidation())}\n\`\`\``);
console.log("Wrote docs/game/*.md");
