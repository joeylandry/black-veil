const out = (name: string, text: string) => writeFileSync(`docs/game/${name}`, `${text.trim()}\n`);
const cname = (id: string) => characters.find((character) => character.id === id)?.name ?? id;

/** The one set of objective labels used in every generated document, so a reader learns them once. */
const TYPE_ORDER = ["MONEY", "FIND", "SWAP", "LEARN A SECRET", "KEEP A SECRET", "LEARN A STORY", "DEAL", "HOST TASK", "VIAL"] as const;
type TypeLabel = (typeof TYPE_ORDER)[number];
const TYPE_MEANING: Record<TypeLabel, string> = {
  MONEY: "Finish the night with at least a stated amount in $100 bills.",
  FIND: "Find a named object in a shared room and type the code on its tag.",
  SWAP: "Trade a carried item with one named guest and type the code on the item received.",
  "LEARN A SECRET": "Earn another guest's small secret. Two named people can leak it.",
  "KEEP A SECRET": "Your own small secret: tell the guest you chose, hide it from the rival. Nothing to type.",
  "LEARN A STORY": "Get one piece of a story from named guests and type the key word or name.",
  DEAL: "Do a small deal with a named guest; a printed slip proves it and you type its code.",
  "HOST TASK": "Do something for real in the room, tap Claim this point, then ask Bartend Joe for the word.",
  VIAL: "A survivor offers a marker to the Butler, or the Butler sells the House's single vial.",
};
function typeOf(objective: { id: string; kind: string; check: { kind: string } }): TypeLabel {
  switch (objective.check.kind) {
    case "money": return "MONEY";
    case "approval": return "HOST TASK";
    case "keep": return "KEEP A SECRET";
    case "vial-attempt":
    case "butler-sale": return "VIAL";
    case "pattern": return objective.id.endsWith("-secret") ? "LEARN A SECRET" : "LEARN A STORY";
    default: return objective.kind === "find" ? "FIND" : objective.kind === "swap" ? "SWAP" : "DEAL";
  }
}
