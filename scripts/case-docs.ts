/**
 * Writes docs/story/02-exhibits-preview.md: every exhibit's full text, its finding and
 * accepted answers, and its sprint slot, so the whole file can be proofread in one place
 * without clicking through ten weeks. Contains the answers: staff eyes only.
 *
 *   npm run case:docs
 */
import { writeFileSync } from "node:fs";
import { exhibits } from "@/data/case/exhibits";
import { sprints } from "@/data/case/sprints";
import { findingAnswers } from "@/data/case/answers";
import type { Block } from "@/data/case/types";

const clean = (text: string) => text.replace(/\{\{x:(\d+)\}\}/g, (_, n) => "█".repeat(Math.min(Number(n), 20)));

function block(b: Block): string {
  switch (b.t) {
    case "masthead":
      return `**${b.name}** · _${b.line}_`;
    case "headline":
      return `### ${b.text}`;
    case "deck":
      return `_${b.text}_`;
    case "byline":
      return `_${b.text}_`;
    case "p":
      return clean(b.text);
    case "fields":
      return ["| | |", "|---|---|", ...b.rows.map(([k, v]) => `| ${k} | ${clean(v)} |`)].join("\n");
    case "table":
      return [`| ${b.head.join(" | ")} |`, `|${b.head.map(() => "---").join("|")}|`, ...b.rows.map((r) => `| ${r.map(clean).join(" | ")} |`), b.note ? `\n_${b.note}_` : ""].join("\n");
    case "image":
      return `![${b.alt}](../../public${b.src})\n_${b.caption}_`;
    case "stamp":
      return `**[STAMP: ${b.text}]**`;
    case "sign":
      return `— ${b.name}, ${b.title}`;
    case "margin":
      return `> _(in the margin)_ ${b.text}`;
    case "box":
      return `> **${b.title}**\n>\n${b.text.map((t) => `> ${clean(t)}`).join("\n>\n")}`;
    case "statement":
      return `**${b.who}** (${b.role}):\n\n${b.text.map((t) => `> “${t}”`).join("\n>\n")}`;
    case "wire":
      return `\`${b.meta}\`\n\n${b.lines.map((l) => `    ${l}`).join("\n")}`;
    case "rule":
      return "---";
  }
}

const out: string[] = [
  "# File 245: every exhibit, in order",
  "",
  "_Generated by `npm run case:docs` from `src/data/case/`. Do not edit by hand. **Contains the answers.**_",
  "",
];

for (const exhibit of exhibits) {
  const sprint = sprints.find((s) => s.week === exhibit.week)!;
  out.push(
    `## Week ${String(exhibit.week).padStart(2, "0")} · ${exhibit.number} · ${exhibit.title}`,
    "",
    `_${exhibit.dated} · ${exhibit.kind}_ · ${exhibit.summary}`,
    "",
    ...exhibit.blocks.flatMap((b) => [block(b), ""]),
    `**Finding:** ${exhibit.finding.prompt}${exhibit.finding.help ? ` _(${exhibit.finding.help})_` : ""}`,
    `**Accepted:** ${findingAnswers[exhibit.week].join(" · ")}`,
    "",
    `**Work order ${sprint.workOrder} · ${sprint.simulation.title}** (${sprint.simulation.labId ? `lab: ${sprint.simulation.labId}` : "simulation not written yet"})`,
    "",
    `Condition: ${exhibit.damage}`,
    "",
    sprint.simulation.pretext,
    "",
    "**Adds to “What the file says so far”:**",
    "",
    ...exhibit.notes.map((n) => `- ${n}`),
    "",
  );
}

writeFileSync("docs/story/02-exhibits-preview.md", out.join("\n"));
console.log("Wrote docs/story/02-exhibits-preview.md");
